export const moreAwsServices = categories.flatMap(([category, color, list]) =>
  list.map(([id, label, prefix, extra = '']) => {
    const file = prefix ? `${prefix}-${id}` : id;
    const words = `${prefix} ${id.replaceAll('-', ' ')} ${extra}`.trim();
    return [id, label, file, category, words, color] as const;
  }),
);
