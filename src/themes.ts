/** Colours for the 3D board. Service tiles mix the theme base with their own colour. */
export interface ScenePalette {
  sky: readonly [string, string, string];
  glow: string;
  fog: string;
  grid: readonly [string, string];
  gridOpacity: number;
  /** Tile body base and how strongly the service colour tints it (0–1). */
  tile: string;
  tileTint: number;
  /** Inset top face base and service tint. */
  face: string;
  faceTint: number;
  /** Wire outline base and service tint; groups use their boundary colour. */
  outline: string;
  outlineTint: number;
  group: string;
  groupOpacity: number;
  shadow: string;
  shadowOpacity: number;
  selected: string;
  edge: string;
  edgeHover: string;
  edgeSelected: string;
  haloOpacity: number;
  /** Bright pulses that travel along connections. */
  flow: string;
  port: string;
  handle: string;
  guide: string;
  nodeLabel: { background: string; border: string; text: string };
  edgeLabel: { background: string; text: string };
  groupLabel: string;
  glyph: string;
  note: { paper: string; text: string };
  text: string;
  ambient: number;
  /** Decoration painted into the static sky (also visible in PNG exports). */
  backdrop?: Backdrop;
  /** Font family for board captions; defaults to system-ui. */
  labelFont?: string;
  /** Canvas filter for service icons drawn on the board, e.g. grayscale. */
  iconFilter?: string;
  /** Strip node colours: tiles, boundaries and notes use theme colours only. */
  monochrome?: boolean;
  /** Connection line width in pixels (default 1.6). */
  edgeWidth?: number;
  /** Marching data-flow dashes: pixel sizes and speed in world units/s. */
  flowStyle?: { width: number; dash: number; gap: number; speed: number };
}
export type Backdrop = 'synthwave' | 'matrix' | 'solar' | 'zen' | 'halftone';
/** Animated layer behind the editor chrome; off with reduced motion or the toggle. */
export type Ambient = 'neon' | 'rain' | 'embers' | 'petals' | 'grain';
export interface Theme {
  id: string;
  name: string;
  dark: boolean;
  /** Short line shown in the theme menu and when the theme is chosen. */
  tagline: string;
  /** Glyph shown beside the brand in the top bar. */
  mark: string;
  /** Menu section: loud showpiece themes or calm everyday ones. */
  group: 'Over the top' | 'Classic';
  ambient?: Ambient;
  /** CSS custom properties consumed by style.css. */
  css: Record<string, string>;
  scene: ScenePalette;
}

